-- Schemat kont użytkowników KOMOREBI.
-- Wykonywany przez obraz postgres przy pierwszym starcie pustej bazy (/docker-entrypoint-initdb.d).
-- Na istniejącej bazie można go uruchomić ręcznie: polecenia są idempotentne.

CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         VARCHAR(120) NOT NULL,
    email         VARCHAR(120) NOT NULL,
    name          VARCHAR(60)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'user'
                  CHECK (role IN ('user', 'admin')),
    level         VARCHAR(20)  NOT NULL DEFAULT 'beginner'
                  CHECK (level IN ('beginner', 'enthusiast', 'master')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ
);

-- Login i e-mail są unikalne bez względu na wielkość liter (logowanie działa na obu).
CREATE UNIQUE INDEX IF NOT EXISTS users_login_lower_key ON users (lower(login));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key ON users (lower(email));

-- Gatunki zaznaczone przy rejestracji (relacja wiele do jednego z kontem).
CREATE TABLE IF NOT EXISTS user_species (
    user_id INTEGER     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    species VARCHAR(20) NOT NULL
            CHECK (species IN ('pinus', 'acer', 'juniperus', 'ficus', 'ulmus')),
    PRIMARY KEY (user_id, species)
);

