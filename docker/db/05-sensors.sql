-- Czujniki wilgotności podłoża przypisane do drzewek konta i ich odczyty (surowa wartość z urządzenia).
-- W bazie leży tylko skrót SHA-256 tokenu czujnika. Polecenia są idempotentne.

CREATE TABLE IF NOT EXISTS sensors (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    tree_id    INTEGER     NOT NULL,
    name       VARCHAR(40) NOT NULL DEFAULT '',
    token_hash CHAR(64)    NOT NULL UNIQUE,
    dry_raw    INTEGER,
    wet_raw    INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, tree_id)
);

CREATE TABLE IF NOT EXISTS sensor_readings (
    sensor_id INTEGER     NOT NULL REFERENCES sensors (id) ON DELETE CASCADE,
    raw       INTEGER     NOT NULL,
    at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sensor_readings_sensor_at ON sensor_readings (sensor_id, at DESC);
